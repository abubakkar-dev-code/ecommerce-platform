const assert = require("node:assert/strict");
const { once } = require("node:events");
const { test, mock } = require("node:test");
const express = require("express");
const mongoose = require("mongoose");
const bcrypt = require("bcryptjs");
const jwt = require("jsonwebtoken");
const crypto = require("node:crypto");

for (const key of [
  "MONGODB_URI", "JWT_SECRET", "CLIENT_ID", "CLIENT_SECRET", "MAIL_HOST",
  "MAIL_USER", "MAIL_PASSWORD", "MAIL_FROM", "CLOUDINARY_CLOUD_NAME",
  "CLOUDINARY_API_KEY", "CLOUDINARY_API_SECRET", "RAZOR_PAY_KEY", "RAZOR_PAY_SECRET",
]) process.env[key] = "user-data-test-only";
process.env.JWT_EXPIRES_IN = "1h";
process.env.CLIENT_CALLBACK_URI = "http://127.0.0.1/google/callback";
process.env.MAIL_PORT = "2525";

const User = require("../dist/models/user.model.js").default;
const Session = require("../dist/models/session.model.js").default;
mock.method(Session, "create", async (session) => session);
mock.method(Session, "updateMany", async () => ({ matchedCount: 0 }));
const AuthToken = require("../dist/models/authToken.js").default;
const { toUserDto } = require("../dist/dto/user.dto.js");
const password = "correct-test-password";
const records = new Map();
const reads = [];
const customerId = new mongoose.Types.ObjectId();
const adminId = new mongoose.Types.ObjectId();
const googleId = new mongoose.Types.ObjectId();
for (const [id, name, role, hasPassword] of [
  [customerId, "Customer", "customer", true],
  [adminId, "Admin", "admin", true],
  [googleId, "Google", "customer", false],
]) records.set(String(id), {
  _id: id, name, email: `${name.toLowerCase()}@example.test`, role, isActive: true,
  googleId: `private-provider-${name}`, __v: 3, createdAt: new Date(),
  ...(hasPassword ? { password: bcrypt.hashSync(password, 4) } : {}),
});

// Keep real Mongoose queries/hydration/save logic; replace only collection I/O.
// This exercises the actual projections generated by select:false and +password.
mock.method(User.collection, "findOne", async (filter, options = {}) => {
  reads.push({ filter, projection: options.projection });
  const record = [...records.values()].find((entry) => Object.entries(filter).every(
    ([key, value]) => String(entry[key]) === String(value),
  ));
  if (!record) return null;
  const result = { ...record };
  for (const [key, included] of Object.entries(options.projection ?? {})) {
    if (included === 0) delete result[key];
  }
  return result;
});
mock.method(User.collection, "insertOne", async (document) => {
  records.set(String(document._id), { ...document });
  return { acknowledged: true, insertedId: document._id };
});
mock.method(User.collection, "updateOne", async (filter, update) => {
  const record = records.get(String(filter._id));
  assert.ok(record, "only fixture documents can be updated");
  Object.assign(record, update.$set ?? {});
  for (const key of Object.keys(update.$unset ?? {})) delete record[key];
  return { acknowledged: true, matchedCount: 1, modifiedCount: 1 };
});
const resetToken = "a".repeat(64);
const resetHash = crypto.createHash("sha256").update(resetToken).digest("hex");
let resetAvailable = true;
mock.method(AuthToken, "exists", async ({ token }) => token === resetHash && resetAvailable ? { _id: customerId } : null);
mock.method(AuthToken, "findOneAndDelete", async ({ token }) => {
  if (token !== resetHash || !resetAvailable) return null;
  resetAvailable = false;
  return { userId: customerId, expiresAt: new Date(Date.now() + 60_000) };
});
mock.method(AuthToken, "create", async (record) => record);
const mail = mock.method(require("../dist/services/sendmail.js"), "passwordResetLink", async () => {});
const userRoutes = require("../dist/utils/routes/user.routes.js").default;
const { googleCallback } = require("../dist/controllers/user.controller.js");
const passport = require("../dist/config/passport.js").default;
const errors = require("../dist/middleware/error.middleware.js").default;
const tokenFor = (id) => jwt.sign({ userId: String(id) }, process.env.JWT_SECRET, { expiresIn: "5m" });
const publicUser = (record) => ({ _id: String(record._id), name: record.name, email: record.email, role: record.role });
const assertDto = (actual, record) => assert.deepEqual(actual, publicUser(record));

test("Phase A user DTOs and password query isolation", async (t) => {
  const app = express();
  app.use(express.json());
  app.use("/api/users", userRoutes);
  app.get("/test/oauth/:id", (req, _res, next) => { req.user = { _id: req.params.id }; next(); }, googleCallback);
  app.use(errors);
  const server = app.listen(0, "127.0.0.1");
  await once(server, "listening");
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (path, method = "GET", body, id) => fetch(base + path, {
    method, headers: { "Content-Type": "application/json", ...(id ? { Authorization: `Bearer ${tokenFor(id)}` } : {}) },
    ...(body ? { body: JSON.stringify(body) } : {}), redirect: "manual",
  });
  try {
    await t.test("normal document and lean queries exclude hashes and provider IDs; explicit selection works", async () => {
      for (const user of [await User.findById(customerId), await User.findOne({ _id: customerId }).lean()]) {
        assert.equal(user.password, undefined);
        assert.equal(user.googleId, undefined);
      }
      const selected = await User.findById(customerId).select("+password");
      assert.equal(await bcrypt.compare(password, selected.password), true);
      assert.equal(selected.googleId, undefined);
      assertDto(toUserDto(selected), records.get(String(customerId)));
    });

    await t.test("allowlist ignores internal and future fields, even on newly created documents", () => {
      const fixture = records.get(String(customerId));
      assertDto(toUserDto({ ...fixture, refreshTokenHash: "private", sessions: ["private"], futureSecret: "private" }), fixture);
      assertDto(toUserDto(new User(fixture)), fixture);
    });

    await t.test("registration returns a DTO while persisting a bcrypt hash", async () => {
      const response = await request("/api/users/register", "POST", {
        name: "New Customer", email: "new@example.test", password,
      });
      assert.equal(response.status, 201);
      const body = await response.json();
      const record = records.get(body.data._id);
      assertDto(body.data, record);
      assert.notEqual(record.password, password);
      assert.equal(await bcrypt.compare(password, record.password), true);
    });

    for (const id of [customerId, adminId]) {
      await t.test(`login preserves token/user contract and hides selected hashes (${id})`, async () => {
        const record = records.get(String(id));
        const start = reads.length;
        const response = await request("/api/users/login", "POST", { email: record.email, password });
        assert.equal(response.status, 200);
        const body = await response.json();
        assertDto(body.data.user, record);
        assert.deepEqual(Object.keys(body.data).sort(), ["token", "user"]);
        const claims = jwt.verify(body.data.token, process.env.JWT_SECRET);
        assert.equal(claims.userId, String(id));
        assert.equal(claims.exp - claims.iat, 3600);
        assert.notEqual(reads.slice(start).at(-1).projection?.password, 0);
      });
    }

    await t.test("profile reads and edits return DTOs and do not erase unselected credentials", async () => {
      const record = records.get(String(customerId));
      const previousHash = record.password;
      let response = await request("/api/users/profile", "GET", undefined, customerId);
      assert.equal(response.status, 200);
      assertDto((await response.json()).data, record);
      response = await request("/api/users/update-profile", "PUT", { name: "Updated Customer" }, customerId);
      assert.equal(response.status, 201);
      assertDto((await response.json()).data, record);
      assert.equal(record.password, previousHash);
      assert.equal(record.googleId, "private-provider-Customer");
    });

    await t.test("password change explicitly reads the hash and returns no user secrets", async () => {
      let response = await request("/api/users/update-password", "PUT", {
        currentPassword: "wrong", newPassword: "changed-password",
      }, customerId);
      assert.equal(response.status, 401);
      response = await request("/api/users/update-password", "PUT", {
        currentPassword: password, newPassword: "changed-password",
      }, customerId);
      assert.equal(response.status, 200);
      assert.equal((await response.json()).data, null);
      assert.equal(await bcrypt.compare("changed-password", records.get(String(customerId)).password), true);
    });

    await t.test("reset assigns a new hash without selecting the old hash and returns a DTO", async () => {
      const start = reads.length;
      const response = await request(`/api/users/reset-password?token=${resetToken}`, "PUT", {
        newPassword: "reset-password", confirmPassword: "reset-password",
      });
      assert.equal(response.status, 201);
      const record = records.get(String(customerId));
      assertDto((await response.json()).data, record);
      assert.equal(await bcrypt.compare("reset-password", record.password), true);
      const replay = await request(`/api/users/reset-password?token=${resetToken}`, "PUT", {
        newPassword: "replay-password", confirmPassword: "replay-password",
      });
      assert.equal(replay.status, 400);
      assert.ok(reads.slice(start).every((query) => query.projection.password === 0));
    });

    await t.test("Google-only accounts reject password verification cleanly", async () => {
      const record = records.get(String(googleId));
      for (const [path, body, id] of [
        ["/api/users/login", { email: record.email, password }, undefined],
        ["/api/users/update-password", { currentPassword: password, newPassword: "changed-password" }, googleId],
      ]) {
        const response = await request(path, id ? "PUT" : "POST", body, id);
        assert.equal(response.status, 401);
        assert.equal((await response.json()).success, false);
      }
    });

    await t.test("OAuth lookup/callback still work without querying credentials", async () => {
      const start = reads.length;
      const outcome = await new Promise((resolve) => passport._strategy("google")._verify(
        "unused", "unused", { id: "private-provider-Google", displayName: "Google",
          emails: [{ value: "google@example.test", verified: true }] },
        (error, identity) => resolve({ error, identity }),
      ));
      assert.equal(outcome.error, null);
      assert.equal(outcome.identity.password, undefined);
      assert.equal(outcome.identity.googleId, undefined);
      const response = await request(`/test/oauth/${googleId}`);
      assert.equal(response.status, 302);
      assert.equal(new URL(response.headers.get("location")).search, "");
      const token = response.headers.getSetCookie()[0].split(";")[0].split("=")[1];
      assert.equal(jwt.verify(token, process.env.JWT_SECRET).userId, String(googleId));
      assert.ok(reads.slice(start).every((query) => query.projection.password === 0));
    });

    await t.test("forgot-password still works without reading a password or sending mail", async () => {
      const start = reads.length;
      const response = await request("/api/users/forgot-password", "POST", { email: "customer@example.test" });
      assert.equal(response.status, 200);
      assert.equal((await response.json()).data, null);
      assert.equal(mail.mock.callCount(), 1);
      assert.ok(reads.slice(start).every((query) => query.projection.password === 0));
    });
  } finally {
    await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
    mock.restoreAll();
  }
});
